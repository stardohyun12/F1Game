"""House-only studio ground cut; offline preparation, no editor calls.

Read the original serialized studio meshes, preserve UVs, and subtract the
foundation footprint. The original mesh assets and other buildings stay intact.
Run: python -X utf8 tools/art/house_studio_ground.py
"""
import json
import re
import struct
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'art/_review/2026-10-30-house-floor'
SOURCE = ROOT / 'F1Studio/Assets/Scenes/Studio_Building_Mats'


def read_mesh(path):
    text = path.read_text(encoding='utf-8')
    count = int(re.search(r'm_VertexCount: (\d+)', text)[1])
    data = bytes.fromhex(re.search(r'_typelessdata: ([0-9a-f]+)', text)[1])
    channels = re.findall(r'- stream: (\d+)\s+offset: (\d+)\s+format: (\d+)\s+dimension: (\d+)', text)
    assert [tuple(map(int, c)) for c in channels[:5]] == [
        (0, 0, 0, 3), (0, 12, 0, 3), (0, 24, 0, 4), (0, 0, 0, 0), (0, 40, 0, 2)], 'Unsupported vertex layout'
    assert len(data) == count * 48
    vertices = list(struct.iter_unpack('<12f', data))
    assert re.search(r'm_IndexFormat: 0', text), 'Expected UInt16 indices'
    raw = bytes.fromhex(re.search(r'm_IndexBuffer: ([0-9a-f]+)', text)[1])
    indices = struct.unpack('<' + 'H' * (len(raw) // 2), raw)
    return vertices, [indices[i:i+3] for i in range(0, len(indices), 3)]


def split(poly, axis, bound, sign):
    inside, outside = [], []
    for a, b in zip(poly, poly[1:] + poly[:1]):
        da, db = sign * (a[axis] - bound), sign * (b[axis] - bound)
        (inside if da >= 0 else outside).append(a)
        if (da >= 0) != (db >= 0):
            t = da / (da - db)
            p = tuple(x + t * (y - x) for x, y in zip(a, b))
            inside.append(p)
            outside.append(p)
    return inside, outside


def area(poly):
    return abs(sum(a[0]*b[2] - b[0]*a[2] for a, b in zip(poly, poly[1:]+poly[:1]))) / 2


def carve(vertices, triangles, bounds):
    kept, removed = [], 0.0
    for tri in triangles:
        poly = [vertices[i] for i in tri]
        for axis, bound, sign in ((0, bounds[0], 1), (0, bounds[1], -1), (2, bounds[2], 1), (2, bounds[3], -1)):
            if not poly:
                break
            poly, outside = split(poly, axis, bound, sign)
            if len(outside) >= 3 and area(outside) > 1e-10:
                # Independently check the source triangle's affine UV plane.
                a, b, c = [vertices[i] for i in tri]
                det = (b[0]-a[0])*(c[2]-a[2])-(c[0]-a[0])*(b[2]-a[2])
                for v in outside:
                    u = ((v[0]-a[0])*(c[2]-a[2])-(c[0]-a[0])*(v[2]-a[2]))/det
                    w = ((b[0]-a[0])*(v[2]-a[2])-(v[0]-a[0])*(b[2]-a[2]))/det
                    assert all(abs(v[k]-(a[k]+u*(b[k]-a[k])+w*(c[k]-a[k]))) < 1e-6 for k in (10, 11))
                kept.extend([outside[0], outside[i], outside[i+1]] for i in range(1, len(outside)-1) if area([outside[0], outside[i], outside[i+1]]) > 1e-10)
        if poly:
            removed += area(poly)
    return kept, removed


def prepare():
    OUT.mkdir(parents=True, exist_ok=True)
    f = json.loads((ROOT / 'tools/art/house_home_site.json').read_text())['foundation']
    bounds = [f['x_min'], f['x_max'], -f['blender_y_max'], -f['blender_y_min']]
    code = ['''// Generated by tools/art/house_studio_ground.py; house review only.
if (!Application.dataPath.Replace("\\\\", "/").EndsWith("/F1Studio/Assets")) throw new System.Exception("F1Studio only");
if (UnityEditor.EditorApplication.isPlaying || UnityEngine.SceneManagement.SceneManager.GetActiveScene().name != "Studio_Building") throw new System.Exception("Studio edit mode required");
var floorHouse = GameObject.Find("STUDIO/STUDIO_Slot/house_home");
if (!floorHouse || floorHouse.transform.position.sqrMagnitude > 0.000001f || Quaternion.Angle(floorHouse.transform.rotation, Quaternion.identity) > .001f || (floorHouse.transform.lossyScale-Vector3.one).sqrMagnitude > .000001f) throw new System.Exception("House must be active at studio origin with identity transform");
''']
    proof = {'foundation_unity_xz': bounds, 'meshes': {}, 'scope': 'house_home studio only; source meshes untouched'}
    all_tris = []
    for name in ('ground', 'road'):
        vertices, triangles = read_mesh(SOURCE / f'ST_{name}_mesh.asset')
        kept, removed = carve(vertices, triangles, bounds)
        original_area = sum(area([vertices[i] for i in tri]) for tri in triangles)
        remaining_area = sum(area(t) for t in kept)
        _, residual = carve([v for t in kept for v in t], [tuple(range(i, i+3)) for i in range(0, len(kept)*3, 3)], bounds)
        assert abs(original_area - remaining_area - removed) < 1e-6
        assert residual < 1e-8 and removed > 0
        expected = (bounds[1]-bounds[0]) * ((bounds[3]-bounds[2]) if name == 'ground' else bounds[3]-1.5)
        assert abs(removed - expected) < 1e-5
        # Heights stay on the original surface; UVs were verified in carve().
        assert all(abs(v[1] - vertices[0][1]) < 1e-8 for t in kept for v in t)
        proof['meshes'][name] = dict(before_tris=len(triangles), after_tris=len(kept), y=vertices[0][1], before_area=original_area, after_area=remaining_area, removed_area=removed, residual_overlap_area=residual, uv_affine_check=True)
        all_tris.extend(kept)
        def vec(v, start, n):
            return f'new Vector{n}(' + ','.join(format(x, '.9g')+'f' for x in v[start:start+n]) + ')'
        flat = [v for tri in kept for v in tri]
        cname = 'ST_Ground' if name == 'ground' else 'ST_Road'
        code.append('''{
var groundObject = GameObject.Find("STUDIO/%s");
if (!groundObject || groundObject.transform.position.sqrMagnitude > .000001f || Quaternion.Angle(groundObject.transform.rotation, Quaternion.identity) > .001f || (groundObject.transform.lossyScale-Vector3.one).sqrMagnitude > .000001f) throw new System.Exception("Unexpected studio ground transform");
var groundPath = "Assets/Art/Review/house_home/ST_%s_house_cut.asset";
var cutMesh = AssetDatabase.LoadAssetAtPath<Mesh>(groundPath);
if (!cutMesh) { cutMesh = new Mesh(); AssetDatabase.CreateAsset(cutMesh, groundPath); }
cutMesh.Clear();
''' % (cname, name))
        for field, start, n in (('vertices', 0, 3), ('normals', 3, 3), ('tangents', 6, 4), ('uv', 10, 2)):
            code.append(f'cutMesh.{field} = new Vector{n}[] {{' + ','.join(vec(v, start, n) for v in flat) + '};')
        code.append('cutMesh.triangles = new int[] {' + ','.join(map(str, range(len(flat)))) + '};')
        code.append('''cutMesh.RecalculateBounds(); EditorUtility.SetDirty(cutMesh);
groundObject.GetComponent<MeshFilter>().sharedMesh = cutMesh;
var groundCollider = groundObject.GetComponent<MeshCollider>(); if (groundCollider) groundCollider.sharedMesh = cutMesh;
EditorUtility.SetDirty(groundObject);
}
''')
    code.append('AssetDatabase.SaveAssets();')
    snippet = '\n'.join(code)
    (OUT / 'apply.cs').write_text(snippet + '\nUnityEditor.SceneManagement.EditorSceneManager.SaveScene(UnityEngine.SceneManagement.SceneManager.GetActiveScene());\nreturn "house ground cut saved";\n', encoding='utf-8')
    # The cut is a house review fixture. Restore before reviewing another asset.
    (OUT / 'restore.cs').write_text('''if (!Application.dataPath.Replace("\\\\", "/").EndsWith("/F1Studio/Assets") || UnityEngine.SceneManagement.SceneManager.GetActiveScene().name != "Studio_Building" || UnityEditor.EditorApplication.isPlaying) return "FAIL: Studio edit mode required";
foreach (var nm in new[] { "ground", "road" }) {
var go = GameObject.Find("STUDIO/" + (nm == "ground" ? "ST_Ground" : "ST_Road"));
if (!go) throw new System.Exception("Missing studio ground");
var mf = go.GetComponent<MeshFilter>();
if (AssetDatabase.GetAssetPath(mf.sharedMesh) != "Assets/Art/Review/house_home/ST_" + nm + "_house_cut.asset") continue;
var original = AssetDatabase.LoadAssetAtPath<Mesh>("Assets/Scenes/Studio_Building_Mats/ST_" + nm + "_mesh.asset");
if (!original) throw new System.Exception("Missing original ground mesh");
mf.sharedMesh = original; var mc = go.GetComponent<MeshCollider>(); if (mc) mc.sharedMesh = original;
EditorUtility.SetDirty(go);
}
UnityEditor.SceneManagement.EditorSceneManager.SaveScene(UnityEngine.SceneManagement.SceneManager.GetActiveScene());
return "original studio ground restored";
''', encoding='utf-8')
    proof['pass'] = True
    (OUT / 'geometry.json').write_text(json.dumps(proof, indent=2), encoding='utf-8')
    im = Image.new('RGB', (1000, 540), '#ece9df'); d = ImageDraw.Draw(im)
    for col, after in enumerate((False, True)):
        ox = col * 500 + 250
        def pt(x, z): return ox + x*13, 280-z*13
        d.text((col*500+20, 16), 'AFTER: geometry proposal (not Unity capture)' if after else 'BEFORE: serialized studio geometry', fill='#1d3638')
        tris = all_tris if after else [[v[i] for i in t] for nm in ('ground', 'road') for v, ts in [read_mesh(SOURCE/f'ST_{nm}_mesh.asset')] for t in ts]
        for t in tris: d.polygon([pt(v[0], v[2]) for v in t], fill='#b4ac8e', outline='#78775f')
        d.rectangle([pt(bounds[0], bounds[3]), pt(bounds[1], bounds[2])], outline='#bd5342', width=3)
        d.text((col*500+20, 510), 'red = foundation footprint', fill='#1d3638')
    im.save(OUT/'sheet.png')
    (OUT/'index.html').write_text('<!doctype html><meta charset="utf-8"><title>House floor geometry</title><h1>집 바닥 중복 제거 — 정적 계산 미리보기</h1><p>도현 승인 필요. Unity 적용·촬영·판정 전. 빨간 경계 안 스튜디오 지면·도로만 제거하며 집 모델은 그대로입니다.</p><img src="sheet.png" width="1000"><p><a href="geometry.json">계산 증거</a></p>', encoding='utf-8')
    return snippet, proof


if __name__ == '__main__':
    _, result = prepare()
    print(json.dumps(result, ensure_ascii=False))
